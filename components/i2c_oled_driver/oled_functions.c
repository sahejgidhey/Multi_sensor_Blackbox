void buffer_merge(uint8_t *buffer_main , uint8_t *buffer_fn , int size)
{
    //buffer_main is the one which is printed on screen
    //buffer temp is the buffer which has the updated elements on screen
    //Size is size of the buffer 

    for(int i = 0 ; i < size ; i++)
    {
        buffer_main[i] = buffer_main[i] | buffer_fn[i];
    }
    //this loop goes through each of 8 bit hexadecimal int both arrays and merege them together using Bitwise OR(|) operater

}

// this function will format the bits into 8bit for pages
void bit_format(uint8_t *format_arr, uint8_t format_arr_size, uint32_t input_bit, uint8_t space)
{

    input_bit = input_bit << space; //this will add space to the bit
    uint32_t temp_bit = input_bit; //this temp bit will be used to format and add bits to array 

    for(int i = 0 ; i < format_arr_size ; i++)
    {

        temp_bit = temp_bit >> 8; // this will remove the 8bits 
        temp_bit = temp_bit << 8; // this will add zeros inplace of those 8 bits
        format_arr[i] = (uint8_t)(input_bit ^ temp_bit); // this will put the first 8 bits in array
        input_bit = input_bit >> 8; // this will removes the bits which are added to array
        temp_bit = temp_bit >> 8; // this will remove the 0 bits from the start 
    }

}

//this function will print the fomated bit array on oled
void bit_format_print(uint8_t *buffer_temp , uint8_t *format_arr , uint8_t format_arr_size , int bufferOffset , int col)
{
    for(int i = 0 ; i < format_arr_size ; i++)
    {

        if(bufferOffset > 1024)
        {
            break;
        }

        buffer_temp[bufferOffset + col] = format_arr[i]; // this add the bits to the index where it need to go 
        bufferOffset = bufferOffset + OLED_H_RES; // this will tell to print in which page

    }
}


void text_print(uint8_t *buffer_temp, char text[] , int text_size , uint8_t page, uint8_t front_space, uint8_t top_space)
{

    int bufferOffset = 0;
    bufferOffset = bufferOffset + (OLED_H_RES * page); // this will tell the starting page
    bufferOffset = bufferOffset + front_space; // this will move the space in front before printing

    uint8_t format_arr[3] = {0};
    int index = 0;// this the index where the column of font will be printed

    for(int i = 0 ; i < text_size-1 ; i++)
    {
        int font_char = ((int)text[i]); // this gets the int value of char and index of character in array
        
        // this if esle statement block is used to manage the font according to the font array
        if(font_char >= 48 && font_char <= 57)
        {
            font_char -= 48;
        }
        else if(font_char >= 65 && font_char <= 90)
        {
            font_char -= 55;
        }
        else if(font_char == 37)
        {
            font_char = 36;
        }
        else if(font_char == 39)
        {
            font_char = 37;
        }
        else if(font_char == 46)
        {
            font_char = 38;
        }
        else if(font_char >= 97 && font_char <= 122)
        {
            font_char -= 87;
        }
        else
        {
            font_char = -1;
        }

        for(int col = 0 ; col < 10 ; col++)
        {

            // this helps in printing space between words
            if(font_char < 0)
            {
                index += 4;
                break;
            }

            if(font[font_char][col] == 0 && font_char >= 0)
            {
                break;
            } // this will skip the 0 bits after the font 

            bit_format(format_arr , sizeof(format_arr) , font[font_char][col] , top_space);
            bit_format_print(buffer_temp , format_arr , sizeof(format_arr) , bufferOffset , index);
            index++; //this increament the index of the bit format
        }

        index+=2; // this will add space between character
    }

}